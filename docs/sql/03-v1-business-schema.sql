-- 仅创建缺失表；不删除、清空或覆盖第一阶段表与数据。
-- MySQL 8.0.16+ / InnoDB；库存和单据时间由 UTC 会话写入。

CREATE TABLE IF NOT EXISTS inbound_order (
    id BIGINT NOT NULL AUTO_INCREMENT,
    order_no VARCHAR(64) NOT NULL,
    warehouse_id BIGINT NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    remark VARCHAR(500) NULL,
    created_by BIGINT NOT NULL,
    confirmed_by BIGINT NULL,
    confirmed_at TIMESTAMP(3) NULL,
    cancelled_by BIGINT NULL,
    cancelled_at TIMESTAMP(3) NULL,
    created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_inbound_order_no UNIQUE (order_no),
    CONSTRAINT fk_inbound_order_warehouse FOREIGN KEY (warehouse_id) REFERENCES warehouse(id),
    CONSTRAINT fk_inbound_order_creator FOREIGN KEY (created_by) REFERENCES app_user(id),
    CONSTRAINT ck_inbound_order_status CHECK (status IN ('PENDING','COMPLETED','CANCELLED')),
    KEY idx_inbound_warehouse_status_created (warehouse_id, status, created_at, id),
    KEY idx_inbound_status_created (status, created_at, id),
    KEY idx_inbound_created (created_at, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

