CREATE TABLE IF NOT EXISTS stocktake_order_item (
    id BIGINT NOT NULL AUTO_INCREMENT,
    order_id BIGINT NOT NULL,
    sku_id BIGINT NOT NULL,
    snapshot_physical BIGINT NOT NULL,
    snapshot_available BIGINT NOT NULL,
    snapshot_locked BIGINT NOT NULL,
    counted_physical BIGINT NOT NULL,
    created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_stocktake_order_item_order_sku UNIQUE (order_id, sku_id),
    CONSTRAINT fk_stocktake_order_item_order FOREIGN KEY (order_id) REFERENCES stocktake_order(id),
    CONSTRAINT fk_stocktake_order_item_sku FOREIGN KEY (sku_id) REFERENCES sku(id),
    CONSTRAINT ck_stocktake_order_item_nonnegative CHECK (snapshot_physical >= 0 AND snapshot_available >= 0 AND snapshot_locked >= 0 AND counted_physical >= 0),
    CONSTRAINT ck_stocktake_order_item_snapshot CHECK (snapshot_physical = snapshot_available + snapshot_locked),
    KEY idx_stocktake_order_item_sku_order (sku_id, order_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS stock_flow (
    id BIGINT NOT NULL AUTO_INCREMENT,
    warehouse_id BIGINT NOT NULL,
    sku_id BIGINT NOT NULL,
    biz_type VARCHAR(16) NOT NULL,
    biz_id BIGINT NOT NULL,
    flow_type VARCHAR(32) NOT NULL,
    delta_physical BIGINT NOT NULL,
    delta_available BIGINT NOT NULL,
    delta_locked BIGINT NOT NULL,
    before_physical BIGINT NOT NULL,
    before_available BIGINT NOT NULL,
    before_locked BIGINT NOT NULL,
    after_physical BIGINT NOT NULL,
    after_available BIGINT NOT NULL,
    after_locked BIGINT NOT NULL,
    operator_id BIGINT NOT NULL,
    created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT fk_stock_flow_warehouse FOREIGN KEY (warehouse_id) REFERENCES warehouse(id),
    CONSTRAINT fk_stock_flow_sku FOREIGN KEY (sku_id) REFERENCES sku(id),
    CONSTRAINT fk_stock_flow_operator FOREIGN KEY (operator_id) REFERENCES app_user(id),
    CONSTRAINT ck_stock_flow_biz_type CHECK (biz_type IN ('INBOUND','OUTBOUND','TRANSFER','STOCKTAKE')),
    CONSTRAINT ck_stock_flow_type CHECK (flow_type IN ('INBOUND','OUTBOUND_LOCK','OUTBOUND_RELEASE','OUTBOUND','TRANSFER_LOCK','TRANSFER_RELEASE','TRANSFER_OUT','TRANSFER_IN','STOCKTAKE_ADJUST')),
    CONSTRAINT ck_stock_flow_before CHECK (before_physical >= 0 AND before_available >= 0 AND before_locked >= 0 AND before_physical = before_available + before_locked),
    CONSTRAINT ck_stock_flow_after CHECK (after_physical >= 0 AND after_available >= 0 AND after_locked >= 0 AND after_physical = after_available + after_locked),
    CONSTRAINT ck_stock_flow_delta CHECK (after_physical = before_physical + delta_physical AND after_available = before_available + delta_available AND after_locked = before_locked + delta_locked),
    KEY idx_stock_flow_warehouse_sku_created (warehouse_id, sku_id, created_at, id),
    KEY idx_stock_flow_biz (biz_type, biz_id, created_at, id),
    KEY idx_stock_flow_type_created (flow_type, created_at, id),
    KEY idx_stock_flow_created (created_at, id),
    KEY idx_stock_flow_sku (sku_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS stock_alert (
    id BIGINT NOT NULL AUTO_INCREMENT,
    warehouse_id BIGINT NOT NULL,
    sku_id BIGINT NOT NULL,
    available_stock BIGINT NOT NULL,
    safety_stock BIGINT NOT NULL,
    status VARCHAR(16) NOT NULL,
    triggered_at TIMESTAMP(3) NOT NULL,
    resolved_at TIMESTAMP(3) NULL,
    created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_stock_alert_warehouse_sku UNIQUE (warehouse_id, sku_id),
    CONSTRAINT fk_stock_alert_warehouse FOREIGN KEY (warehouse_id) REFERENCES warehouse(id),
    CONSTRAINT fk_stock_alert_sku FOREIGN KEY (sku_id) REFERENCES sku(id),
    CONSTRAINT ck_stock_alert_quantity CHECK (available_stock >= 0 AND safety_stock >= 0),
    CONSTRAINT ck_stock_alert_status CHECK (status IN ('ACTIVE','RESOLVED')),
    KEY idx_stock_alert_status_triggered (status, triggered_at, id),
    KEY idx_stock_alert_warehouse_status (warehouse_id, status, triggered_at, id),
    KEY idx_stock_alert_sku_status (sku_id, status, triggered_at, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
